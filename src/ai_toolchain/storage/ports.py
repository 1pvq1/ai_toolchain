"""Ports consumed by storage services; adapters are supplied at construction."""

from pathlib import Path
from typing import Callable, Protocol


class Tree(Protocol):
    files: list[Path]
    directories: list[Path]
    links: list[Path]


class FileSystem(Protocol):
    def exists(self, path: Path) -> bool: ...
    def is_dir(self, path: Path) -> bool: ...
    def is_file(self, path: Path) -> bool: ...
    def is_link(self, path: Path) -> bool: ...
    def is_symlink(self, path: Path) -> bool: ...
    def same_target(self, path: Path, target: Path) -> bool: ...
    def readlink(self, path: Path) -> str: ...
    def scan(self, path: Path) -> Tree: ...
    def size(self, path: Path) -> int: ...
    def same_volume(self, first: Path, second: Path) -> bool: ...
    def free_bytes(self, path: Path) -> int: ...
    def mkdir(self, path: Path) -> None: ...
    def rename(self, source: Path, target: Path) -> None: ...
    def hardlink(self, source: Path, target: Path) -> None: ...
    def symlink(self, source: Path, target: Path) -> None: ...
    def unlink(self, path: Path) -> None: ...
    def rmdir(self, path: Path) -> None: ...
    def copy_new(self, source: Path, target: Path, on_bytes: Callable[[int], None]) -> None: ...
    def read_bytes(self, path: Path) -> bytes: ...
    def write_atomic(self, path: Path, data: bytes) -> None: ...
    def hide(self, path: Path) -> None: ...


class Hasher(Protocol):
    def digest(self, path: Path) -> str: ...


class Journal(Protocol):
    root: Path
    def new_id(self) -> str: ...
    def save(self, record: dict) -> None: ...
    def load(self, migration_id: str) -> dict: ...
    def list_records(self) -> list[dict]: ...
    def legacy_records(self) -> list[dict]: ...
    def archive_legacy(self, migration_id: str) -> None: ...


class ProgressSink(Protocol):
    def stage(self, name: str, total_bytes: int) -> None: ...
    def advance(self, amount: int) -> None: ...
    def done(self) -> None: ...
    def message(self, value: str) -> None: ...


class ProcessGuard(Protocol):
    def assert_stopped(self, roots: list[Path]) -> None: ...
